import { expect, test } from "./fixtures";
import { propertyToday, shiftDate } from "../src/stay-types";

test("owner creates and removes a private block from the listing manager", async ({ page }, testInfo) => {
  const today = propertyToday();
  const listing = { id: 7, venue_id: 1, title: "Moj apartman", city: "Beograd", description: "Ceo stan za odmor i posao.", offer_type: "short_stay", area_sqm: 50, rooms: 2, price_cents: 6500, currency: "EUR", contact_email: "owner@example.com", is_published: true, timezone: "Europe/Belgrade" };
  let blocked = false;
  let exports = 0;
  let subscribed = false;
  await page.route("**/api/owner/properties/7/occupancy-feed", route => {
    expect(route.request().headers().authorization).toBe("Bearer owner-session");
    if (route.request().method() === "POST") subscribed = true;
    if (route.request().method() === "DELETE") subscribed = false;
    return route.fulfill({ json: { active: subscribed, ...(route.request().method() === "POST" ? { path: "/occupancy-feeds/test-secret.ics" } : {}) } });
  });
  await page.addInitScript(() => localStorage.setItem("bookica_token", "owner-session"));
  await page.route("**/api/owner/properties/7/occupancy.ics", route => {
    expect(route.request().headers().authorization).toBe("Bearer owner-session");
    exports++;
    return exports === 1 ? route.fulfill({ status: 503, json: { detail: "unavailable" } }) : route.fulfill({ contentType: "text/calendar", body: "BEGIN:VCALENDAR\r\nVERSION:2.0\r\nEND:VCALENDAR\r\n" });
  });
  const block = { id: 1, venue_id: 1, check_in: today, check_out: shiftDate(today, 3), reason: "Renoviranje", active: true, created_at: new Date().toISOString() };
  const calendar = `BEGIN:VCALENDAR\r\nVERSION:2.0\r\nBEGIN:VEVENT\r\nDTSTART;VALUE=DATE:${today.replaceAll("-", "")}\r\nDTEND;VALUE=DATE:${block.check_out.replaceAll("-", "")}\r\nEND:VEVENT\r\nEND:VCALENDAR\r\n`;
  await page.route("**/api/owner/properties/7/occupancy-import**", route => {
    expect(route.request().headers().authorization).toBe("Bearer owner-session");
    expect(route.request().postDataJSON()).toEqual({ content: calendar });
    const applied = !route.request().url().endsWith("/preview");
    if (applied) blocked = true;
    return route.fulfill({ json: { ranges: [{ check_in: today, check_out: block.check_out, status: "ready" }], ignored: 0, clipped: 0, applied, created: applied ? 1 : 0 } });
  });
  await page.route("**/api/auth/me", route => route.fulfill({ json: { id: 1, email: "owner@example.com", role: "owner" } }));
  await page.route("**/api/venues", route => route.fulfill({ json: [] }));
  await page.route("**/api/promotions/active", route => route.fulfill({ json: [] }));
  await page.route("**/api/owner/stats", route => route.fulfill({ json: { total_venues: 1, total_resources: 0, total_reservations: 0, total_revenue_cents: 0, reservations_by_status: {}, top_resources: [] } }));
  await page.route("**/api/owner/venues", route => route.fulfill({ json: [{ id: 1, name: "Moj objekat", address: "Centar", owner_id: 1 }] }));
  await page.route("**/api/owner/resources", route => route.fulfill({ json: [] }));
  await page.route("**/api/owner/reservations", route => route.fulfill({ json: [] }));
  await page.route("**/api/owner/properties?*", route => route.fulfill({ json: { items: [listing], total: 1, limit: 20, offset: 0, has_next: false } }));
  await page.route("**/api/owner/properties/7/stay-blocks?*", route => route.fulfill({ json: { items: blocked ? [block] : [], total: blocked ? 1 : 0, has_next: false } }));
  await page.route("**/api/owner/properties/7/stay-blocks", route => {
    expect(route.request().postDataJSON()).toMatchObject({ check_in: today, check_out: block.check_out, reason: block.reason });
    expect(route.request().postDataJSON().request_id).toMatch(/^[0-9a-f-]{36}$/);
    blocked = true; return route.fulfill({ status: 201, json: block });
  });
  await page.route("**/api/owner/properties/7/stay-blocks/1", route => { blocked = false; return route.fulfill({ status: 204 }); });
  await page.goto("/owner");
  await page.getByRole("button", { name: "Blokade: Moj apartman" }).click();
  expect(exports).toBe(0);
  await page.getByRole("button", { name: "Preuzmi zauzetost (.ics)" }).click();
  await expect(page.getByRole("alert")).toContainText("Izvoz nije uspeo");
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Preuzmi zauzetost (.ics)" }).click();
  expect((await download).suggestedFilename()).toBe("bookica-occupancy-7.ics");
  await expect(page.getByText(/Preuzimanje je pokrenuto/)).toBeVisible();
  await expect(page.getByText(/bez automatske sinhronizacije/)).toBeVisible();
  await page.getByRole("button", { name: "Podesi iCal pretplatu" }).click();
  await page.getByRole("button", { name: "Kreiraj pretplatni link" }).click();
  expect(subscribed).toBe(false);
  await page.getByRole("button", { name: "Potvrdi promenu", exact: true }).click();
  await expect(page.getByLabel("Tajni pretplatni link")).toHaveValue(/\/api\/occupancy-feeds\/test-secret\.ics$/);
  await page.getByRole("button", { name: "Opozovi pretplatu", exact: true }).click();
  expect(subscribed).toBe(true);
  await page.getByRole("button", { name: "Potvrdi promenu", exact: true }).click();
  await expect(page.getByText("Pretplata nije aktivna.", { exact: true })).toBeVisible();
  await expect(page.getByLabel("Tajni pretplatni link")).toHaveCount(0);
  await page.getByLabel("Kraj blokade").fill(block.check_out);
  await page.getByLabel("Privatni razlog (opciono)").fill(block.reason);
  await page.getByRole("button", { name: "Blokiraj termin" }).click();
  await expect(page.getByText("Aktivnih blokada: 1")).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("owner-stay-blocks.png"), fullPage: true });
  await page.getByRole("button", { name: "Ukloni blokadu" }).click();
  expect(blocked).toBe(true);
  await page.getByRole("button", { name: "Potvrdi uklanjanje" }).click();
  await expect(page.getByText("Aktivnih blokada: 0")).toBeVisible();
  await page.getByLabel("iCal fajl (.ics, do 100 KB)").setInputFiles({ name: "availability.ics", mimeType: "text/calendar", buffer: Buffer.from(calendar) });
  await page.getByRole("button", { name: "Pregledaj uvoz" }).click();
  await expect(page.getByText(/Nova blokada/)).toBeVisible();
  expect(blocked).toBe(false);
  await page.getByRole("button", { name: "Potvrdi uvoz blokada" }).click();
  await expect(page.getByText(/Uvoz je završen/)).toBeVisible();
  await expect(page.getByText("Aktivnih blokada: 1")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("owner-calendar-import.png"), fullPage: true });
});
